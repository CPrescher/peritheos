def numeric(value: Any) -> bool:
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and math.isfinite(value)
    )


def comparison_rows(assessment: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    return [
        p
        for p in assessment.get("parameters", [])
        if numeric(p.get("published")) and numeric(p.get("refit"))
    ]


def fit_role(assessment: Mapping[str, Any], name: str) -> str:
    fit = assessment.get("fit", {})
    for field, label in (
        ("fixed_parameters", "Fixed/adopted"),
        ("free_parameters", "Free"),
    ):
        values = fit.get(field)
        if isinstance(values, (list, Mapping)) and name in values:
            return label
    return "See protocol"


def figure_signature(assessment: Mapping[str, Any]) -> str:
    data = [
        (
            p["parameter"],
            p["published"],
            p["refit"],
            p.get("published_error", p.get("published_sigma")),
            p.get("refit_error", p.get("refit_sigma")),
            fit_role(assessment, p["parameter"]),
        )
        for p in comparison_rows(assessment)
    ]
    payload = json.dumps(
        data, ensure_ascii=False, separators=(",", ":")
    ) + inspect.getsource(comparison_svg)
    return hashlib.sha256(payload.encode()).hexdigest()


def current_figure(payload: bytes, assessment: Mapping[str, Any]) -> bool:
    """Check input and SVG-body hashes without depending on Matplotlib's version."""
    marker = re.search(
        rb"<!-- peritheos-comparison data=([a-f0-9]{64}) body=([a-f0-9]{64}) -->\n",
        payload,
    )
    if not marker or marker[1].decode() != figure_signature(assessment):
        return False
    original = payload[: marker.start()] + payload[marker.end() :]
    if hashlib.sha256(original).hexdigest() != marker[2].decode():
        return False
    try:
        svg = ElementTree.fromstring(payload)
    except ElementTree.ParseError:
        return False
    return svg.tag == "{http://www.w3.org/2000/svg}svg"


def comparison_svg(assessment: Mapping[str, Any]) -> bytes | None:
    """Plot coefficients and recorded error widths without inferring confidence."""
    rows = comparison_rows(assessment)
    if not rows:
        return None
    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    columns = 1 if len(rows) <= 4 else 2
    lines = math.ceil(len(rows) / columns)
    style = {
        "svg.hashsalt": "peritheos-reconstruction-v1",
        "svg.fonttype": "none",
        "font.family": "DejaVu Sans",
        "font.size": 11,
    }
    with plt.rc_context(style):
        figure, axes = plt.subplots(
            lines,
            columns,
            figsize=(7.2 if columns == 1 else 10, 2.15 * lines),
            squeeze=False,
            layout="constrained",
        )
        for ax, row in zip(axes.flat, rows):
            source, refit = row["published"], row["refit"]
            ax.plot([source, refit], [1, 0], color="#aab4c0", linewidth=1, zorder=1)
            ax.scatter([source], [1], color="#245b8a", marker="o", s=45, zorder=2)
            ax.scatter([refit], [0], color="#ae4c14", marker="D", s=40, zorder=2)
            for side, y, color in (
                ("published", 1, "#245b8a"),
                ("refit", 0, "#ae4c14"),
            ):
                error = row.get(side + "_error", row.get(side + "_sigma"))
                if numeric(error) and error > 0:
                    ax.errorbar(
                        row[side], y, xerr=error, color=color, capsize=3, fmt="none"
                    )
            ax.set_yticks([0, 1], ["Reconstruction", "Source / target"])
            limits = [0, source, refit]
            for side in ("published", "refit"):
                error = row.get(side + "_error", row.get(side + "_sigma"))
                if numeric(error) and error > 0:
                    limits.extend([row[side] - error, row[side] + error])
            low, high = min(limits), max(limits)
            span = high - low or 1
            ax.set_xlim(low - 0.08 * span, high + 0.08 * span)
            ax.set_ylim(-0.55, 1.55)
            ax.axvline(0, color="#c3cad2", linewidth=0.7, zorder=0)
            ax.set_title(
                f"{row['parameter']} — {fit_role(assessment, row['parameter'])}",
                loc="left",
                fontsize=11,
            )
            ax.set_xlabel("Value in the named audit's units")
            ax.ticklabel_format(
                axis="x", style="sci", scilimits=(-3, 4), useOffset=False
            )
            ax.grid(axis="x", color="#e7eaee", linewidth=0.6)
            for spine in ("top", "right", "left"):
                ax.spines[spine].set_visible(False)
        for ax in list(axes.flat)[len(rows) :]:
            ax.set_visible(False)
        buffer = io.BytesIO()
        figure.savefig(
            buffer,
            format="svg",
            metadata={
                "Date": None,
                "Creator": "Peritheos reconstruction reports",
                "Title": "Stored source and reconstructed coefficients",
                "Description": "Stored coefficients and available reported error widths; confidence conventions remain those of the named audit.",
            },
        )
        plt.close(figure)
    # Keep readable text and a browser font fallback on systems without DejaVu.
    payload = buffer.getvalue().replace(
        b"'DejaVu Sans'", b"'DejaVu Sans', Arial, sans-serif"
    )
    payload = b"\n".join(line.rstrip() for line in payload.splitlines()) + b"\n"
    marker = f"<!-- peritheos-comparison data={figure_signature(assessment)} body={hashlib.sha256(payload).hexdigest()} -->\n".encode()
    return payload.replace(b"?>\n", b"?>\n" + marker, 1)


def explicit_reports(record: Mapping[str, Any], root: Path) -> list[str]:
    """Link only reports explicitly named in existing evidence and present locally."""
    serialized = json.dumps(record, ensure_ascii=False)
    matches = re.findall(
        r"(?:docs/)?((?:literature-reproductions|research)/[^\s\"<>\)]+?\.md(?:#[^\s\"<>\)]+)?)",
        serialized,
    )
    reports = []
    for path in sorted(set(matches)):
        page = (root / "docs" / path.split("#", 1)[0]).resolve()
        if page.is_relative_to((root / "docs").resolve()) and page.is_file():
            reports.append(path)
    return reports


@lru_cache(maxsize=8)
def illustrated_sources(root: Path) -> tuple[tuple[str, str], ...]:
    reports = []
    for path in sorted((root / "docs/literature-reproductions").glob("*.md")):
        content = path.read_text(encoding="utf-8")
        if re.search(r"!\[|<img|<svg|<iframe", content, re.IGNORECASE):
            reports.append((path.relative_to(root / "docs").as_posix(), content))
    return tuple(reports)


def illustrated_mentions(identifier: str, root: Path) -> list[str]:
    """An exact identifier mention is a related discussion, not inferred fit evidence."""
    token = re.compile(
        r"(?<![A-Za-z0-9_])" + re.escape(identifier) + r"(?![A-Za-z0-9_])"
    )
    return [
        path for path, content in illustrated_sources(root) if token.search(content)
    ]


def detail_label(assessment: Mapping[str, Any]) -> str:
    """The headline word, the stored code behind ``untested`` and poor agreement."""
    word = REPRODUCTION_HEADLINES.get(assessment.get("status"), "untested")
    label = f"**{word}**"
    if word == "untested" and assessment.get("status") in UNTESTED_DETAIL:
        label += f" ({UNTESTED_DETAIL[assessment['status']]})"
    if assessment.get("fit", {}).get("data_agreement_status") == "poor":
        label += ", poor data agreement"
    return label


def present(value: Any) -> bool:
    return value not in (None, "", [], {})


def reading_notes(curves: bool, coefficients: bool) -> list[str]:
    """Conventions shared by every section of a page, stated once per page."""
    notes = [
        "Each section opens with the record's reproduction headline and any usage",
        "warning ([label definitions](../eos-labels.md)), then the scope and basis of",
        "the stored check. Only recorded content is shown: missing selections, weights,",
        "errors or conventions are unknown, not zero, and are not inferred. Generating",
        "this page fits nothing and changes no classification or source coefficient.",
        "Every record is also listed by identifier in the",
        "[numerical ledger](../primary-eos-refits.md#records), its",
        f"[machine-readable form]({SOURCE}docs/data/primary-eos-refits.json) and the",
        "[source-audit reports](../source-audits.md).",
    ]
    if curves:
        notes.extend(
            [
                "",
                "**Curves and residuals** replay the full stored source and reconstructed",
                "coefficients on the same recorded audit inputs. Residual = model − input in",
                "the fitted quantity's native units; for pressure, P(model) − P(input) at each",
                "input volume and temperature (isothermal records use their reference",
                "temperature). RMS is an unweighted descriptive error, not a parameter",
                "uncertainty or the weighted fitting objective. With more than five",
                "temperatures, the minimum, middle and maximum isotherms are drawn; residuals",
                "include every selected row. Error bars appear only where all widths are",
                "recoverable and keep the source meaning, including digitization widths.",
                "No uncertainty band is inferred.",
            ]
        )
    if coefficients:
        notes.extend(
            [
                "",
                "**Coefficient graphs** show stored central values and recorded error widths",
                "in the audit's units; each panel includes zero. They are not observation or",
                "residual plots. Fixed/adopted values are constraints, not recovered values.",
                "Tables round an error to two significant digits when its leading digit is 1",
                "or 2, otherwise one, and the value to the error's decimal place; values",
                "without a positive error show at most six significant digits. Full precision",
                "stays in EOSMAT and the ledger.",
            ]
        )
    return notes


def report_page(document: Mapping[str, Any], *, root: Path, comparisons=None) -> str:
    material = document["identifier"]
    previous = root / "docs/primary-eos-refits.md"
    anchors = (
        set(re.findall(r'<a id="([^"]+)"', previous.read_text(encoding="utf-8")))
        if previous.exists()
        else set()
    )
    records = document["eos_records"]
    if comparisons is None:
        comparisons = {r["identifier"]: curve_comparison(document, r) for r in records}
    links = [
        "[All reconstruction reports](index.md)",
        f"[Material and EOS parameters](../material-summaries/{material}.md)",
        f"[EOSMAT record file]({SOURCE}peritheos/data/materials/{quote(material)}.eosmat)",
    ]
    if (root / "peritheos/data/audits" / f"{material}.audit.json").is_file():
        links.append(
            f"[Audit sidecar]({SOURCE}peritheos/data/audits/{quote(material)}.audit.json)"
        )
    lines = [
        f"# {text(document.get('name', material))}: EOS reconstruction reports",
        "",
        GENERATED,
        "",
        " · ".join(links),
        "",
    ]
    if not records:
        lines.append("This material card has no EOS record.")
        return "\n".join(lines) + "\n"
    has_curves = any(comparisons[r["identifier"]][0] is not None for r in records)
    has_tables = any(
        r["evidence"]["reproduction"]["assessment"].get("parameters") for r in records
    )
    lines.extend(
        [
            *reading_notes(has_curves, has_tables),
            "",
            "| EOS record | Reproduction | Warning |",
            "| --- | --- | --- |",
        ]
    )
    for record in records:
        assessment = record["evidence"]["reproduction"]["assessment"]
        warning = headline(record, document)["warning"]
        lines.append(
            f"| [{text(record.get('label', record['identifier']))}](#record-{record['identifier']}) "
            f"| {detail_label(assessment)} | {text(warning) if warning else ''} |"
        )
    for record in records:
        lines.extend(
            record_section(
                document, record, comparisons[record["identifier"]], root, anchors
            )
        )
    page = "\n".join(line.rstrip() for line in lines).rstrip() + "\n"
    return re.sub(r"\n{3,}", "\n\n", page)


def record_section(
    document: Mapping[str, Any],
    record: Mapping[str, Any],
    compared: tuple[Any, str],
    root: Path,
    anchors: set[str],
) -> list[str]:
    """One record: headline and warning, scope and basis, then recorded content only."""
    material = document["identifier"]
    rid = record["identifier"]
    assessment = record["evidence"]["reproduction"]["assessment"]
    validation = record["evidence"].get("scientific_validation", {})
    fit = assessment.get("fit", {})
    comparison, unavailable = compared
    warning = headline(record, document)["warning"]
    lines = [
        "",
        f'<a id="record-{rid}"></a>',
        "",
        f"## {text(record.get('label', rid))}",
        "",
        f"{detail_label(assessment)} · `{rid}` · `{record['model']}` · "
        f"[Coefficients and source](../material-summaries/{material}.md#record-{rid})",
        "",
    ]
    if warning:
        lines.extend([f"**Warning:** {text(warning)}", ""])
    if validation.get("warning"):
        lines.extend(
            [f"**Warning (source review):** {text(validation['warning'])}", ""]
        )
    lines.extend(
        [
            f"**Scope:** {SCOPES[assessment['scope']]}. "
            f"**Basis:** {text(assessment.get('basis', 'No comparison has been assessed.'))}",
            "",
        ]
    )
    status = validation.get("status")
    if status and status != "primary_source_validated":
        lines.extend([f"**Source review:** `{status}`.", ""])
    usage = validation.get("usage_recommendation")
    if usage and not coded(usage):
        lines.extend([f"**Usage:** {text(usage)}", ""])
    # ``parity_not_achieved`` is the ledger's name for ``not_reproduced``.
    if assessment.get("source_status") not in (
        None,
        assessment["status"],
        LEDGER_SYNONYMS.get(assessment["status"]),
    ):
        lines.extend([f"Ledger code: `{assessment['source_status']}`.", ""])
    if assessment.get("qualifications"):
        lines.extend([f"- {text(value)}" for value in assessment["qualifications"]])
        lines.append("")
    if assessment["scope"] == "independent_refit":
        lines.extend(
            [
                "The source/target values below are the stored **Peritheos refit**. Agreement with it does not reproduce the original publication's coefficients.",
                "",
            ]
        )
    visible = {
        k: fit[k]
        for k in (
            "dataset_identifiers",
            "observations",
            "fit_kind",
            "selection",
            "objective",
            "weighting",
            "absolute_sigma",
            "free_parameters",
            "fixed_parameters",
            "fixed_values",
            "validation_fixed_parameters",
        )
        if k in fit
    }
    # An empty list says nothing was declared; "no fixed parameter" is only
    # informative next to a declared list of free parameters.
    method = {
        k: v
        for k, v in visible.items()
        if present(v)
        or (k == "fixed_parameters" and present(fit.get("free_parameters")))
    }
    if method:
        lines.extend(["### Method", "", *metadata(rounded_metadata(method)), ""])
    if isinstance(comparison, DiagnosticComparison):
        lines.extend(["### Curves and residuals", ""])
        if comparison.partial_replay:
            lines.extend(
                [
                    "**Partial replay — available subsets only.**",
                    "",
                    text(comparison.note),
                    "",
                ]
            )
        lines.extend(
            [
                *themed_images(
                    f"Source and refit curves with native-coordinate residuals for {rid}",
                    f"figures/{rid}-curves.svg",
                ),
                "",
                "| Output / replay scope | Points | Residual units | Source RMS | Refit RMS |",
                "| --- | ---: | --- | ---: | ---: |",
                *[
                    f"| {text(p.title)} | {len(p.x)} | {text(p.unit)} | {number(p.rms('source'), 3)} | {number(p.rms('refit'), 3)} |"
                    for p in comparison.panels
                ],
                "",
            ]
        )
        if not comparison.partial_replay and comparison.note:
            lines.extend([text(comparison.note), ""])
    elif comparison is not None:
        lines.extend(
            [
                "### Curves and residuals",
                "",
                *themed_images(
                    f"Original/source and refitted curves with pressure residuals for {rid}",
                    f"figures/{rid}-curves.svg",
                ),
                "",
                "| Fit | Pressure RMS error (GPa) |",
                "| --- | ---: |",
                f"| {'Stored Peritheos refit (target)' if assessment['scope'] == 'independent_refit' else 'Original / source fit'} | {number(comparison.source_rmse, 3)} |",
                f"| Reconstruction / refit | {number(comparison.refit_rmse, 3)} |",
                "",
                f"Both fits use the same {len(comparison.series.pressure)} recovered audit input rows. "
                f"**Volume coordinate:** {text(comparison.series.volume_column)}. "
                f"**Row selection:** {text(comparison.series.selection)}.",
                "",
                *([text(comparison.note), ""] if comparison.note else []),
            ]
        )
    else:
        if comparison_rows(assessment):
            reason = text(unavailable).rstrip(".")
            lines.extend([f"No curve plot: {reason}.", ""])
        recorded = [
            f"{label} {number(fit[key], 3)}"
            for key, label in (
                ("published_rmse_gpa", "source fit"),
                ("rmse_gpa", "reconstruction"),
            )
            if numeric(fit.get(key))
        ]
        if recorded:
            lines.extend(
                [
                    "Recorded pressure RMS error (GPa), in the audit's own coordinates "
                    f"and objective: {'; '.join(recorded)}.",
                    "",
                ]
            )
    if assessment.get("parameters"):
        lines.extend(["### Coefficients", ""])
        if comparison_rows(assessment):
            lines.extend(
                [
                    *themed_images(
                        f"Source/target and reconstructed central values for {rid}",
                        f"figures/{rid}.svg",
                    ),
                    "",
                ]
            )
        lines.extend(
            [
                "| Parameter | Source / target | Source error | Reconstruction | Reconstruction error | Fit role |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
        )
        for row in assessment["parameters"]:
            published, published_error = value_error(
                row["published"],
                row.get("published_error", row.get("published_sigma")),
                row.get("display_decimal_places"),
            )
            refit, refit_error = value_error(
                row["refit"],
                row.get("refit_error", row.get("refit_sigma")),
                row.get("display_decimal_places"),
            )
            values = (
                row["parameter"],
                published,
                published_error,
                refit,
                refit_error,
                fit_role(assessment, row["parameter"]),
            )
            lines.append("| " + " | ".join(text(v) for v in values) + " |")
        lines.append("")
    diagnostics = {k: v for k, v in fit.items() if k not in visible}
    if diagnostics:
        lines.extend(
            details(
                "Recorded diagnostics, covariance and additional protocol",
                rounded_metadata(diagnostics),
            )
        )
    evidence = []
    if "investigation-" + rid in anchors:
        evidence.append(
            f"- [Earlier detailed record investigation](../primary-eos-refits.md#investigation-{rid})."
        )
    supporting = explicit_reports(record, root)
    for page in supporting:
        evidence.append(
            f"- [Supporting source report: {text(Path(page.split('#')[0]).stem)}](../{page})."
        )
    for page in illustrated_mentions(rid, root):
        if page not in {p.split("#", 1)[0] for p in supporting}:
            evidence.append(
                f"- [Related illustrated report explicitly naming this EOS: {text(Path(page).stem)}](../{page})."
            )
    if evidence:
        lines.extend(["### More evidence", "", *evidence, ""])
    return lines


def generated_outputs(root: Path = ROOT, *, plots: bool = True) -> dict[Path, bytes]:
    outputs: dict[Path, bytes] = {}
    gaps = []
    partials = []
    total_records = total_curves = total_coefficients = 0
    headers = [*REPRODUCTION_VALUES, "warning"]
    totals = dict.fromkeys(headers, 0)
    rows = []
    for path in sorted((root / "peritheos/data/materials").glob("*.eosmat")):
        document = load_eosmat(path)
        material = document["identifier"]
        count = 0
        curve_count = 0
        comparisons = {}
        for record in document["eos_records"]:
            assessment = record["evidence"]["reproduction"]["assessment"]
            expected = report_links(material, record["identifier"])
            if any(assessment.get(key) != value for key, value in expected.items()):
                raise ValueError(
                    f"Missing or inconsistent report links: {record['identifier']}; standardize reconstruction metadata first"
                )
            comparison, reason = curve_comparison(document, record)
            comparisons[record["identifier"]] = (comparison, reason)
            if comparison is None and comparison_rows(assessment):
                gaps.append((material, record["identifier"], reason))
            if comparison is not None:
                if (
                    isinstance(comparison, DiagnosticComparison)
                    and comparison.partial_replay
                ):
                    partials.append((material, record["identifier"], comparison))
                curve_count += 1
                if plots:
                    relative = Path("figures") / (record["identifier"] + "-curves.svg")
                    existing = root / "docs/reconstruction-reports" / relative
                    figure = existing.read_bytes() if existing.exists() else b""
                    if not current_curve(figure, comparison):
                        figure = curve_svg(comparison)
                    outputs[relative] = figure
            if comparison_rows(assessment):
                count += 1
                if plots:
                    relative = Path("figures") / (record["identifier"] + ".svg")
                    existing = root / "docs/reconstruction-reports" / relative
                    figure = existing.read_bytes() if existing.exists() else b""
                    if not current_figure(figure, assessment):
                        figure = comparison_svg(assessment)
                    assert figure is not None
                    outputs[relative] = figure
        outputs[Path(material + ".md")] = report_page(
            document, root=root, comparisons=comparisons
        ).encode()
        counts = dict.fromkeys(headers, 0)
        for record in document["eos_records"]:
            check = headline(record, document)
            counts[check["reproduction"]] += 1
            counts["warning"] += bool(check["warning"])
        for key in headers:
            totals[key] += counts[key]
        rows.append(
            f"| [{text(document.get('name', material))}]({material}.md) | "
            f"{len(document['eos_records'])} | "
            + " | ".join(str(counts[key] or "") for key in headers)
            + " |"
        )
        total_records += len(document["eos_records"])
        total_curves += curve_count
        total_coefficients += count
    index = [
        "# EOS reconstruction reports",
        "",
        GENERATED,
        "",
        "One page per material and one section per EOS record. Each section opens with",
        "the record's reproduction headline and any usage warning; the words are defined",
        "in [EOS labels](../eos-labels.md). Plots replay stored coefficients on recorded",
        "audit inputs; generating the reports fits nothing and changes no classification.",
        "Plots switch between light and dark versions with the documentation theme.",
        "",
        "Record `report_url` links point to Read the Docs **latest**, which can change",
        "after later audits; repository-relative `report_path` links work offline.",
        "",
        "| Material | Records | "
        + " | ".join(REPRODUCTION_VALUES)
        + " | With warning |",
        "| --- | ---: | " + " | ".join("---:" for _ in headers) + " |",
        *rows,
        f"| **All materials** | **{total_records}** | "
        + " | ".join(f"**{totals[key]}**" for key in headers)
        + " |",
        "",
        f"{total_curves} of {total_coefficients} records with a stored coefficient "
        "comparison have curve/residual plots, including "
        f"{len(partials)} explicitly partial replays listed below.",
    ]
    if partials:
        index.extend(
            [
                "",
                "## Partial replays",
                "",
                "These plots cover the named available subsets only, not the complete recorded objective or the author's workflow. Each report names the omitted inputs.",
                "",
                "| EOS record | Available plot scope |",
                "| --- | --- |",
                *[
                    f"| [{text(rid)}]({material}.md#record-{rid}) | {text('; '.join(p.title for p in c.panels))} |"
                    for material, rid, c in partials
                ],
            ]
        )
    if gaps:
        index.extend(
            [
                "",
                "## Remaining curve/residual replay gaps",
                "",
                "These are report-rendering gaps, not a finding that source observations do not exist. The named audit remains authoritative. Specialized pressure reductions, joint objectives or model mappings need an explicit replay adapter before a plot can be shown here.",
                "",
                "| EOS record | Replay gap |",
                "| --- | --- |",
                *[
                    f"| [{text(rid)}]({material}.md#record-{rid}) | {text(reason)} |"
                    for material, rid, reason in gaps
                ],
            ]
        )
    outputs[Path("index.md")] = ("\n".join(index) + "\n").encode()
    if plots:
        for path, light in list(outputs.items()):
            if path.suffix == ".svg":
                outputs[Path(dark_path(path.as_posix()))] = dark_svg(light)
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated_outputs()
    stale = []
    for path in (OUTPUT / "figures").glob("*.svg"):
        if path.relative_to(OUTPUT) not in outputs and (
            b"<!-- peritheos-curves " in path.read_bytes()
            or b"<!-- peritheos-dark " in path.read_bytes()
        ):
            stale.append(path.relative_to(OUTPUT))
            if not args.check:
                path.unlink()
    for relative, payload in outputs.items():
        path = OUTPUT / relative
        if path.exists() and path.read_bytes() == payload:
            continue
        stale.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
    if args.check and stale:
        for path in stale:
            print(f"Reconstruction report needs regeneration: {path}")
        return 1
    print(
        f"{'Checked' if args.check else 'Generated'} {sum(p.suffix == '.md' for p in outputs)} pages and {sum(p.suffix == '.svg' for p in outputs)} figures; {len(stale)} changed."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
