"""Build readable, linked reports from recorded EOSMAT assessments, without fitting.

Run ``python -m scripts.generate_reconstruction_reports``; ``--check`` verifies
the pages and deterministic SVG comparisons. Figures show recorded coefficient
central values, never invented observations, fitted curves or uncertainty bands.
"""

from __future__ import annotations

import argparse
import hashlib
import inspect
import io
import json
import math
import re
from collections.abc import Mapping
from functools import lru_cache
from pathlib import Path
from typing import Any
from urllib.parse import quote
from xml.etree import ElementTree

from peritheos import load_eosmat
from scripts.generate_material_summaries import details, metadata, text
from scripts.reconstruction_links import report_links

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/reconstruction-reports"
GENERATED = "<!-- Generated by scripts.generate_reconstruction_reports; edit EOSMAT instead. -->"
SOURCE = "https://github.com/CPrescher/peritheos/blob/main/"
OUTCOMES = {
    "parity": "Coefficient parity achieved",
    "similar": "Numerically similar, with qualifications",
    "not_reproduced": "Parity not achieved for this comparison",
    "not_refittable": "Complete independent refit unavailable",
    "source_reconstruction": "Source calculation reconstructed",
    "not_assessed": "Not assessed",
}
SCOPES = {
    "parameter_agreement": "Comparison with the source parameterization",
    "independent_refit": "Reproduction of a stored independent Peritheos refit",
    "source_equation": "Reconstruction of a source equation or calculation",
    "author_workflow": "Reproduction of the documented author workflow",
}


def numeric(value: Any) -> bool:
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and math.isfinite(value)
    )


def comparison_rows(assessment: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    return [
        p
        for p in assessment.get("parameters", [])
        if numeric(p.get("published")) and numeric(p.get("refit"))
    ]


def fit_role(assessment: Mapping[str, Any], name: str) -> str:
    fit = assessment.get("fit", {})
    for field, label in (
        ("fixed_parameters", "Fixed/adopted"),
        ("free_parameters", "Free"),
    ):
        values = fit.get(field)
        if isinstance(values, (list, Mapping)) and name in values:
            return label
    return "See protocol"


def figure_signature(assessment: Mapping[str, Any]) -> str:
    data = [
        (
            p["parameter"],
            p["published"],
            p["refit"],
            fit_role(assessment, p["parameter"]),
        )
        for p in comparison_rows(assessment)
    ]
    payload = json.dumps(
        data, ensure_ascii=False, separators=(",", ":")
    ) + inspect.getsource(comparison_svg)
    return hashlib.sha256(payload.encode()).hexdigest()


def current_figure(payload: bytes, assessment: Mapping[str, Any]) -> bool:
    """Check input and SVG-body hashes without depending on Matplotlib's version."""
    marker = re.search(
        rb"<!-- peritheos-comparison data=([a-f0-9]{64}) body=([a-f0-9]{64}) -->\n",
        payload,
    )
    if not marker or marker[1].decode() != figure_signature(assessment):
        return False
    original = payload[: marker.start()] + payload[marker.end() :]
    if hashlib.sha256(original).hexdigest() != marker[2].decode():
        return False
    try:
        svg = ElementTree.fromstring(payload)
    except ElementTree.ParseError:
        return False
    return svg.tag == "{http://www.w3.org/2000/svg}svg"


def comparison_svg(assessment: Mapping[str, Any]) -> bytes | None:
    """Plot central values on separate axes with zero visible; no uncertainty inference."""
    rows = comparison_rows(assessment)
    if not rows:
        return None
    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import pyplot as plt

    columns = 1 if len(rows) <= 4 else 2
    lines = math.ceil(len(rows) / columns)
    style = {
        "svg.hashsalt": "peritheos-reconstruction-v1",
        "svg.fonttype": "none",
        "font.family": "DejaVu Sans",
        "font.size": 11,
    }
    with plt.rc_context(style):
        figure, axes = plt.subplots(
            lines,
            columns,
            figsize=(7.2 if columns == 1 else 10, 2.15 * lines),
            squeeze=False,
            layout="constrained",
        )
        for ax, row in zip(axes.flat, rows):
            source, refit = row["published"], row["refit"]
            ax.plot([source, refit], [1, 0], color="#aab4c0", linewidth=1, zorder=1)
            ax.scatter([source], [1], color="#245b8a", marker="o", s=45, zorder=2)
            ax.scatter([refit], [0], color="#ae4c14", marker="D", s=40, zorder=2)
            ax.set_yticks([0, 1], ["Reconstruction", "Source / target"])
            low, high = min(0, source, refit), max(0, source, refit)
            span = high - low or 1
            ax.set_xlim(low - 0.08 * span, high + 0.08 * span)
            ax.set_ylim(-0.55, 1.55)
            ax.axvline(0, color="#c3cad2", linewidth=0.7, zorder=0)
            ax.set_title(
                f"{row['parameter']} — {fit_role(assessment, row['parameter'])}",
                loc="left",
                fontsize=11,
            )
            ax.set_xlabel("Value in the named audit's units")
            ax.ticklabel_format(
                axis="x", style="sci", scilimits=(-3, 4), useOffset=False
            )
            ax.grid(axis="x", color="#e7eaee", linewidth=0.6)
            for spine in ("top", "right", "left"):
                ax.spines[spine].set_visible(False)
        for ax in list(axes.flat)[len(rows) :]:
            ax.set_visible(False)
        buffer = io.BytesIO()
        figure.savefig(
            buffer,
            format="svg",
            metadata={
                "Date": None,
                "Creator": "Peritheos reconstruction reports",
                "Title": "Stored source and reconstructed coefficients",
                "Description": "Central-value comparison only; no observations, residuals or inferred confidence intervals.",
            },
        )
        plt.close(figure)
    # Keep readable text and a browser font fallback on systems without DejaVu.
    payload = buffer.getvalue().replace(
        b"'DejaVu Sans'", b"'DejaVu Sans', Arial, sans-serif"
    )
    payload = b"\n".join(line.rstrip() for line in payload.splitlines()) + b"\n"
    marker = f"<!-- peritheos-comparison data={figure_signature(assessment)} body={hashlib.sha256(payload).hexdigest()} -->\n".encode()
    return payload.replace(b"?>\n", b"?>\n" + marker, 1)


def explicit_reports(record: Mapping[str, Any], root: Path) -> list[str]:
    """Link only reports explicitly named in existing evidence and present locally."""
    serialized = json.dumps(record, ensure_ascii=False)
    matches = re.findall(
        r"(?:docs/)?((?:literature-reproductions|research)/[^\s\"<>\)]+?\.md(?:#[^\s\"<>\)]+)?)",
        serialized,
    )
    reports = []
    for path in sorted(set(matches)):
        page = (root / "docs" / path.split("#", 1)[0]).resolve()
        if page.is_relative_to((root / "docs").resolve()) and page.is_file():
            reports.append(path)
    return reports


@lru_cache(maxsize=8)
def illustrated_sources(root: Path) -> tuple[tuple[str, str], ...]:
    reports = []
    for path in sorted((root / "docs/literature-reproductions").glob("*.md")):
        content = path.read_text(encoding="utf-8")
        if re.search(r"!\[|<img|<svg|<iframe", content, re.IGNORECASE):
            reports.append((path.relative_to(root / "docs").as_posix(), content))
    return tuple(reports)


def illustrated_mentions(identifier: str, root: Path) -> list[str]:
    """An exact identifier mention is a related discussion, not inferred fit evidence."""
    token = re.compile(
        r"(?<![A-Za-z0-9_])" + re.escape(identifier) + r"(?![A-Za-z0-9_])"
    )
    return [
        path for path, content in illustrated_sources(root) if token.search(content)
    ]


def report_page(document: Mapping[str, Any], *, root: Path) -> str:
    material = document["identifier"]
    previous = root / "docs/primary-eos-refits.md"
    anchors = (
        set(re.findall(r'<a id="([^"]+)"', previous.read_text()))
        if previous.exists()
        else set()
    )
    lines = [
        f"# {text(document.get('name', material))}: EOS reconstruction reports",
        "",
        GENERATED,
        "",
        f"[All reconstruction reports](index.md) · [Material and EOS parameters](../material-summaries/{material}.md)",
        "",
        "These reports explain the assessments already stored in EOSMAT. Generating",
        "this page does not refit observations, change classifications or replace source coefficients.",
        "",
        "Use [scientific label definitions](../eos-labels.md) to distinguish coefficient",
        "agreement, source verification, author-workflow reproduction and recommendation for use.",
        "",
        "| EOS record | Recorded outcome | Coefficient comparison |",
        "| --- | --- | --- |",
    ]
    for record in document["eos_records"]:
        assessment = record["evidence"]["reproduction"]["assessment"]
        lines.append(
            f"| [{text(record.get('label', record['identifier']))}](#record-{record['identifier']}) | {OUTCOMES[assessment['status']]} | {'Graph and table' if comparison_rows(assessment) else 'No numeric coefficient pair recorded'} |"
        )
    if not document["eos_records"]:
        lines.extend(
            [
                "",
                "This material card has no stored EOS record and therefore no reconstruction assessment.",
                "",
            ]
        )
    for record in document["eos_records"]:
        rid = record["identifier"]
        assessment = record["evidence"]["reproduction"]["assessment"]
        validation = record["evidence"].get("scientific_validation", {})
        fit = assessment.get("fit", {})
        lines.extend(
            [
                "",
                f'<a id="record-{rid}"></a>',
                "",
                f"## {text(record.get('label', rid))}",
                "",
                f"Record: `{rid}` · Model: `{record['model']}`",
                "",
                f"**Outcome: {OUTCOMES[assessment['status']]}.**",
                "",
                f"**Scope:** {SCOPES[assessment['scope']]}.  ",
                f"**Comparison basis:** {text(assessment.get('basis', 'No comparison has been assessed.'))}",
                "",
                f"[Stored EOS coefficients and source](../material-summaries/{material}.md#record-{rid})",
                "",
                "### What this result establishes",
                "",
                f"**Separate source-review status:** {text(validation.get('status', 'Not specified'))}.  ",
                f"**Usage recommendation:** {text(validation.get('usage_recommendation', 'See the stored EOS qualifications; no recommendation is inferred here.'))}",
                "",
                *[f"- {text(value)}" for value in assessment.get("qualifications", [])],
                "",
                "### Data and reconstruction method",
                "",
            ]
        )
        if assessment["scope"] == "independent_refit":
            lines.extend(
                [
                    "The source/target column below is the stored **Peritheos refit**. Agreement with it does not reproduce the original publication's coefficients.",
                    "",
                ]
            )
        visible = {
            k: fit[k]
            for k in (
                "dataset_identifiers",
                "observations",
                "fit_kind",
                "selection",
                "objective",
                "weighting",
                "absolute_sigma",
                "free_parameters",
                "fixed_parameters",
                "fixed_values",
                "validation_fixed_parameters",
            )
            if k in fit
        }
        if visible:
            lines.extend(metadata(visible))
        lines.extend(
            [
                "",
                "Unspecified selections, weights, fixed values or error conventions remain unknown; they have not been inferred for this report.",
                "",
            ]
        )
        if comparison_rows(assessment):
            lines.extend(
                [
                    "### Source versus reconstruction",
                    "",
                    f"![Source/target and reconstructed central values for {rid}](figures/{rid}.svg)",
                    "",
                    "This is a **coefficient comparison**, not an observation or residual plot.",
                    "Each panel uses its coefficient's audit units and includes zero. Markers show",
                    "stored central values only. Error widths are retained in the table below;",
                    "no confidence interval or uncertainty band is inferred. Fixed/adopted values are constraints.",
                    "",
                ]
            )
        else:
            lines.extend(
                [
                    "### Why no coefficient graph is shown",
                    "",
                    "No numeric source/reconstruction pair is recorded for this assessment. A graph would require information that is not available here; no values or observations have been invented.",
                    "",
                ]
            )
        if assessment.get("parameters"):
            lines.extend(
                [
                    "| Parameter | Source / target | Source error | Reconstruction | Reconstruction error | Fit role |",
                    "| --- | --- | --- | --- | --- | --- |",
                ]
            )
            for row in assessment["parameters"]:
                values = (
                    row["parameter"],
                    row["published"],
                    row.get("published_error", row.get("published_sigma")),
                    row["refit"],
                    row.get("refit_error", row.get("refit_sigma")),
                    fit_role(assessment, row["parameter"]),
                )
                lines.append("| " + " | ".join(text(v) for v in values) + " |")
            lines.extend(
                [
                    "",
                    "Values and reported errors are copied without rounding or conversion from the named audit. Missing errors mean unknown, not zero. Parameter names and volume conventions follow that audit; error widths do not imply a confidence convention.",
                    "",
                ]
            )
        diagnostics = {k: v for k, v in fit.items() if k not in visible}
        if diagnostics:
            lines.extend(
                details(
                    "Recorded diagnostics, covariance and additional protocol",
                    diagnostics,
                )
            )
        lines.extend(["### Detailed evidence and existing plots", ""])
        old_anchor = "investigation-" + rid
        if old_anchor in anchors:
            lines.append(
                f"- [Earlier detailed record investigation](../primary-eos-refits.md#{old_anchor})."
            )
        supporting = explicit_reports(record, root)
        for page in supporting:
            lines.append(
                f"- [Supporting source report: {text(Path(page.split('#')[0]).stem)}](../{page})."
            )
        for page in illustrated_mentions(rid, root):
            if page not in {p.split("#", 1)[0] for p in supporting}:
                lines.append(
                    f"- [Related illustrated report explicitly naming this EOS: {text(Path(page).stem)}](../{page})."
                )
        lines.extend(
            [
                "- [Record-by-record numerical ledger](../primary-eos-refits.md#records).",
                "- [Source-audit reports](../source-audits.md).",
                "",
                "Observation curves and residual plots are provided by the supporting reports where available. Their absence is not filled by a reconstructed curve presented as measured data.",
                "",
                f"[Machine-readable comparison ledger]({SOURCE}docs/data/primary-eos-refits.json) — look up `{rid}`.  ",
                f"[Complete native EOSMAT file]({SOURCE}peritheos/data/materials/{quote(material)}.eosmat).",
                "",
            ]
        )
    return "\n".join(line.rstrip() for line in lines).rstrip() + "\n"


def generated_outputs(root: Path = ROOT, *, plots: bool = True) -> dict[Path, bytes]:
    outputs: dict[Path, bytes] = {}
    index = [
        "# EOS reconstruction reports",
        "",
        GENERATED,
        "",
        "Open a material, then its EOS record. Every bundled record has a direct",
        "section explaining its recorded outcome, comparison basis, method and limitations.",
        "",
        "Coefficient graphs show existing source/reconstructed central values only.",
        "They are not observation/residual plots or new scientific validation.",
        "Supporting source reports retain their detailed explanations and existing plots.",
        "",
        "Public EOSMAT links use Read the Docs **latest**. Repository-relative report paths",
        "support offline and version-specific builds; latest may change after later audits.",
        "New links become live only after the corresponding documentation is published.",
        "",
        "| Material | EOS records | Coefficient graphs |",
        "| --- | ---: | ---: |",
    ]
    for path in sorted((root / "peritheos/data/materials").glob("*.eosmat")):
        document = load_eosmat(path)
        material = document["identifier"]
        count = 0
        for record in document["eos_records"]:
            assessment = record["evidence"]["reproduction"]["assessment"]
            expected = report_links(material, record["identifier"])
            if any(assessment.get(key) != value for key, value in expected.items()):
                raise ValueError(
                    f"Missing or inconsistent report links: {record['identifier']}; standardize reconstruction metadata first"
                )
            if comparison_rows(assessment):
                count += 1
                if plots:
                    relative = Path("figures") / (record["identifier"] + ".svg")
                    existing = root / "docs/reconstruction-reports" / relative
                    figure = existing.read_bytes() if existing.exists() else b""
                    if not current_figure(figure, assessment):
                        figure = comparison_svg(assessment)
                    assert figure is not None
                    outputs[relative] = figure
        outputs[Path(material + ".md")] = report_page(document, root=root).encode()
        index.append(
            f"| [{text(document.get('name', material))}]({material}.md) | {len(document['eos_records'])} | {count} |"
        )
    outputs[Path("index.md")] = ("\n".join(index) + "\n").encode()
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generated_outputs()
    stale = []
    for relative, payload in outputs.items():
        path = OUTPUT / relative
        if path.exists() and path.read_bytes() == payload:
            continue
        stale.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(payload)
    if args.check and stale:
        for path in stale:
            print(f"Reconstruction report needs regeneration: {path}")
        return 1
    print(
        f"{'Checked' if args.check else 'Generated'} {sum(p.suffix == '.md' for p in outputs)} pages and {sum(p.suffix == '.svg' for p in outputs)} coefficient graphs; {len(stale)} changed."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
