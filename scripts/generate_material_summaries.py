"""Generate readable material sheets from EOSMAT and current catalog selections.

Run ``python -m scripts.generate_material_summaries``; ``--check`` detects stale
or missing sheets without writing. The EOSMAT files remain authoritative.
"""

from __future__ import annotations

import argparse
import html
import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any
from urllib.parse import quote

from peritheos import list_materials
from peritheos.eosmat import convert_eosmat, load_eosmat

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/material-summaries"
SOURCE_URL = "https://github.com/CPrescher/peritheos/blob/main/peritheos/data/"
_GENERATED = (
    "<!-- Generated by scripts.generate_material_summaries; edit EOSMAT instead. -->"
)
_LABELS = {
    "temperature_ref": "Reference temperature (K)",
    "experimental_pressure_range_gpa": "Reported pressure coverage (GPa)",
    "experimental_temperature_range_k": "Reported temperature coverage (K)",
    "pressure_range_status": "Coverage provenance",
    "parameter_error_confidence": "Reported error confidence level",
    "determination_method": "Origin of the parameterization",
    "doi": "DOI",
    "source_url": "Source URL",
    "access_url": "Access URL",
    "used_by_eos_records": "Associated EOS records",
}


def text(value: Any) -> str:
    """Keep source text and numbers intact while escaping Markdown tables."""
    if value is None:
        return "Not specified"
    if isinstance(value, (list, tuple)) and all(isinstance(v, str) for v in value):
        value = "; ".join(value) if value else "None declared"
    if isinstance(value, (Mapping, list, tuple)):
        value = json.dumps(value, ensure_ascii=False, allow_nan=False)
    value = html.escape(str(value), quote=False).replace("\\", "\\\\")
    for character in ("|", "`", "*", "_", "[", "]"):
        value = value.replace(character, "\\" + character)
    return value.replace("\r\n", "\n").replace("\n", "<br>")


def metadata(value: Any, depth: int = 0) -> list[str]:
    """Render source qualifications as prose lists rather than JSON syntax."""
    lines = []
    if isinstance(value, Mapping):
        for key, item in value.items():
            label = text(_LABELS.get(key, key.replace("_", " ").capitalize()))
            if isinstance(item, Mapping) or (
                isinstance(item, list) and any(isinstance(v, Mapping) for v in item)
            ):
                lines.append("    " * depth + f"- **{label}:**")
                lines.extend(metadata(item, depth + 1))
            else:
                lines.append("    " * depth + f"- **{label}:** {text(item)}")
    elif isinstance(value, list):
        for item in value:
            lines.extend(metadata(item, depth))
    else:
        lines.append("    " * depth + f"- {text(value)}")
    return lines


def details(label: str, value: Any) -> list[str]:
    return [
        "",
        '<details markdown="1">',
        f"<summary>{label}</summary>",
        "",
        *metadata(value),
        "",
        "</details>",
        "",
    ]


def reconstruction(record: Mapping[str, Any]) -> list[str]:
    """Show the scoped result and its actual coefficient comparison together."""
    assessment = record.get("reproduction", {}).get("assessment")
    if not assessment:
        return []
    lines = [
        "",
        "### Reconstruction",
        "",
        f"**Outcome:** {text(assessment['status'].replace('_', ' '))}.",
        f"**Scope:** {text(assessment['scope'].replace('_', ' '))}.",
        "",
        f"**Comparison basis:** {text(assessment.get('basis', 'Not assessed'))}",
        "",
    ]
    if assessment.get("report_path", "").startswith("docs/reconstruction-reports/"):
        destination = "../" + assessment["report_path"].removeprefix("docs/")
        lines.extend([f"[Open reconstruction report]({destination})", ""])
    elif assessment.get("report_url", "").startswith(("https://", "http://")):
        lines.extend([f"[Open reconstruction report]({assessment['report_url']})", ""])
    if assessment.get("source_status"):
        lines.extend([f"Original audit code: `{assessment['source_status']}`.", ""])
    if assessment.get("qualifications"):
        lines.extend(["**Limitations and qualifications:**", ""])
        lines.extend(f"- {text(value)}" for value in assessment["qualifications"])
        lines.append("")
    rows = assessment.get("parameters", [])
    if rows:
        lines.extend(
            [
                '<details markdown="1">',
                "<summary>Source and reconstructed coefficients</summary>",
                "",
                "These reconstructed values describe the named audit, including failed or",
                "partial reconstructions. They do not replace the EOS parameters above.",
                "For an independent-refit assessment, the source column is the stored",
                "Peritheos refit. Parameter names and volume/temperature conventions follow",
                "the named audit; reported errors retain their original meaning.",
                "",
                "| Parameter | Source value | Source error | Reconstruction value | Reconstruction error | Fit role |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
        )
        fixed = assessment.get("fit", {}).get("fixed_parameters", [])
        free = assessment.get("fit", {}).get("free_parameters", [])
        # Older protocols can describe constraints as prose. Only explicit
        # lists/maps identify names; substring matches must not label a fit role.
        if not isinstance(fixed, (list, Mapping)):
            fixed = []
        if not isinstance(free, (list, Mapping)):
            free = []
        for row in rows:
            lines.append(
                "| "
                + " | ".join(
                    text(value)
                    for value in (
                        row["parameter"],
                        row["published"],
                        row.get("published_error", row.get("published_sigma")),
                        row["refit"],
                        row.get("refit_error", row.get("refit_sigma")),
                        "Fixed/adopted"
                        if row["parameter"] in fixed
                        else "Free"
                        if row["parameter"] in free
                        else "See protocol",
                    )
                )
                + " |"
            )
        lines.extend(
            [
                "",
                "Fixed/adopted coefficients are constraints, not independently reconstructed values.",
                "",
            ]
        )
        if assessment.get("fit"):
            lines.extend(metadata(assessment["fit"]))
        lines.extend(["", "</details>", ""])
    elif assessment.get("fit"):
        lines.extend(
            details(
                "Reconstruction protocol and available diagnostics", assessment["fit"]
            )
        )
    if assessment.get("report"):
        lines.extend(
            [
                f"Machine-readable comparison: `{assessment['report']}` (this record's identifier).",
                "",
            ]
        )
    return lines


def availability(record: Mapping[str, Any], executable: set[str]) -> str:
    if record["identifier"] not in executable:
        return "Document only"
    if record.get("pressure_scale_variant_of"):
        return "Pressure-scale reference variant"
    if (
        record.get("catalog_access") == "explicit_selection"
        or record["scientific_validation"]["status"] != "primary_source_validated"
    ):
        return "Explicit diagnostic selection; not recommended"
    usage = record["scientific_validation"].get("usage_recommendation")
    if usage == "not_recommended_for_quantitative_use":
        return "Executable; not recommended for quantitative use"
    if usage:
        return "Executable; see usage qualifications"
    return "Executable"


def parameters(record: Mapping[str, Any]) -> list[str]:
    lines = [
        "",
        "| Component | Parameter | Value | Reported error | Fixed |",
        "| --- | --- | --- | --- | --- |",
    ]
    for component_name, label in (("eos", "Primary"), ("thermal", "Thermal")):
        component = record.get(component_name)
        if not component:
            continue
        errors = record["parameter_errors"] if component_name == "eos" else {}
        errors = {**errors, **component.get("parameter_errors", {})}
        fixed = set(component.get("fixed_parameters", []))
        if component_name == "eos":
            fixed.update(record["fixed_parameters"])
        for name, value in component["parameters"].items():
            error = errors.get(name)
            displayed = text(value) if value is not None else "null (model convention)"
            lines.append(
                f"| {label} | {text(name)} | {displayed} | "
                f"{text(error) if error is not None else 'Not reported'} | "
                f"{'Yes' if name in fixed else 'Not listed'} |"
            )
    lines.extend(
        [
            "",
            "Values use the source model's parameter units. Primary `V0` uses",
            "the conventional-cell volume declared above. Errors retain their reported",
            "meaning; an absent error is unknown, and absence of covariance does not",
            "establish statistical independence.",
            "",
        ]
    )
    return lines


def coefficient(record: Mapping[str, Any], name: str) -> str:
    """Show stored central values and reported errors without rounding."""
    component = record["eos"]
    if name not in component["parameters"]:
        return "—"
    result = text(component["parameters"][name])
    errors = {**record["parameter_errors"], **component.get("parameter_errors", {})}
    if errors.get(name) is not None:
        result += " ± " + text(errors[name])
    if name in record["fixed_parameters"] or name in component.get(
        "fixed_parameters", []
    ):
        result += " (fixed)"
    return result


def render_material(
    document: Mapping[str, Any], *, executable: set[str], defaults: Mapping[str, str]
) -> str:
    if document.get("format_version") == 4:
        document = convert_eosmat(document, version=3)
    identifier = document["identifier"]
    records = document["eos_records"]
    source = SOURCE_URL + "materials/" + quote(identifier) + ".eosmat"
    lines = [
        f"# {text(document['name'])}",
        "",
        _GENERATED,
        "",
        f"[All materials](index.md) · [Complete EOSMAT source]({source})",
        "",
        "Generated from the material document and the current executable catalog.",
        "Edit the EOSMAT source and regenerate this sheet; this summary does not",
        "replace its full scientific provenance. Source validation, fit reproduction",
        "and recommendation for use are distinct assessments.",
        "",
        "| Material property | Value |",
        "| --- | --- |",
    ]
    for key, label in (
        ("identifier", "Identifier"),
        ("formula", "Formula"),
        ("phase", "Phase"),
        ("aliases", "Aliases"),
        ("formula_units_per_cell", "Formula units per cell"),
        ("cell_contents", "Cell contents"),
        ("symmetry", "Crystal system"),
        ("space_group", "Space group"),
        ("lattice", "Reference lattice"),
    ):
        if key in document:
            lines.append(f"| {label} | {text(document[key])} |")
    for quantity, unit in document["units"].items():
        if unit == "angstrom^3/conventional_unit_cell":
            unit = "Å³ per conventional unit cell"
        lines.append(f"| {text(quantity.capitalize())} unit | {text(unit)} |")
    lines.extend(
        [
            f"| Stored EOS records | {len(records)} |",
            f"| Observation datasets | {len(document.get('datasets', []))} |",
            "",
        ]
    )
    if document.get("notes"):
        lines.extend([text(document["notes"]), ""])
    if document.get("recommendation_hold"):
        lines.extend(
            [
                "## Default selection hold",
                "",
                *metadata(document["recommendation_hold"]),
                "",
            ]
        )
    lines.extend(["## Automatic selections", ""])
    for kind in ("equilibrium", "hugoniot"):
        selected = next(
            (rid for rid, category in defaults.items() if category == kind), None
        )
        lines.append(
            f"- **{kind.capitalize()}:** "
            + (f"[{text(selected)}](#record-{selected})" if selected else "None")
        )
    lines.extend(["", "## EOS comparison", ""])
    if not records:
        lines.extend(
            ["No executable EOS parameterization is stored in this document.", ""]
        )
    else:
        lines.extend(
            [
                "| Record | Model | Reference temperature (K) | Source status | Availability |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
    for record in records:
        rid = record["identifier"]
        model = record["eos"]["type"]
        if record.get("thermal"):
            model += " + " + record["thermal"]["type"]
        lines.append(
            f"| [{text(record['label'])}](#record-{rid}) | {text(model)} | "
            f"{text(record.get('temperature_ref'))} | "
            f"{text(record['scientific_validation']['status'].replace('_', ' '))} | "
            f"{availability(record, executable)} |"
        )
    if records:
        lines.extend(
            [
                "",
                "### Reference coefficients",
                "",
                "| Record | V0 (Å³ per cell) | K0 (GPa) | K0′ |",
                "| --- | --- | --- | --- |",
            ]
        )
        for record in records:
            lines.append(
                f"| [{text(record['label'])}](#record-{record['identifier']}) | "
                + " | ".join(
                    coefficient(record, name) for name in ("V0", "K0", "K0_prime")
                )
                + " |"
            )
        lines.extend(
            [
                "",
                "Errors are shown only when supplied, with their source meaning; a bare",
                "central value does not imply zero uncertainty. A dash means this parameter",
                "is absent from that formulation. Full component tables follow below.",
                "",
            ]
        )
    lines.extend(
        [
            "",
            "Experimental coverage and evaluation limits below are separate source",
            "declarations. Marginal pressure and temperature ranges do not establish",
            "a joint phase-stability domain or authorize extrapolation.",
            "",
        ]
    )
    for record in records:
        rid = record["identifier"]
        lines.extend(
            [
                f'<a id="record-{rid}"></a>',
                "",
                f"## {text(record['label'])}",
                "",
                f"Identifier: `{rid}`.",
                "",
                f"Availability: **{availability(record, executable)}**.",
                "",
            ]
        )
        if rid in defaults:
            lines.extend([f"Automatic selection for {defaults[rid]} calculations.", ""])
        if record.get("pressure_scale_variant_of"):
            parent = record["pressure_scale_variant_of"]
            lines.extend(
                [
                    f"Published pressure-scale alternative of [{text(parent)}]"
                    f"(#record-{parent}); it is not an independent EOS choice.",
                    "",
                ]
            )
        validation = record["scientific_validation"]
        if validation.get("usage_recommendation"):
            lines.extend(
                [
                    "**Usage qualification:** "
                    + text(validation["usage_recommendation"]),
                    "",
                ]
            )
        lines.extend(
            metadata(
                {
                    key: validation[key]
                    for key in (
                        "reproduction_status",
                        "fit_reproduction_status",
                        "original_publication_reproduction_status",
                        "refit_status",
                    )
                    if key in validation
                }
            )
        )
        lines.append("")
        lines.extend(
            metadata(
                {
                    k: record[k]
                    for k in (
                        "record_kind",
                        "determination_method",
                        "equation_kind",
                        "reference",
                        "temperature_ref",
                        "temperature_ref_provenance",
                        "experimental_pressure_range_gpa",
                        "pressure_range_status",
                        "experimental_temperature_range_k",
                        "validity",
                        "loading_path",
                        "branch_kind",
                        "initial_state",
                        "branch_domain",
                        "volume_basis",
                        "parameter_error_confidence",
                    )
                    if k in record
                }
            )
        )
        lines.extend(parameters(record))
        lines.extend(reconstruction(record))
        for name in ("eos", "thermal"):
            if name in record:
                configuration = {
                    k: v
                    for k, v in record[name].items()
                    if k
                    not in {
                        "type",
                        "model",
                        "parameters",
                        "parameter_errors",
                        "fixed_parameters",
                    }
                }
                if configuration:
                    lines.extend(
                        details(f"{name.capitalize()} equation choices", configuration)
                    )
        if record.get("notes"):
            lines.extend([text(record["notes"]), ""])
        if record.get("parameter_covariance") is not None:
            lines.extend(
                ["Parameter covariance is supplied in the complete EOSMAT source.", ""]
            )
        else:
            lines.extend(["Parameter covariance is not supplied.", ""])
        lines.extend(
            details(
                "Scientific validation and usage qualifications",
                record["scientific_validation"],
            )
        )
        if record.get("pressure_calibration"):
            lines.extend(
                details("Pressure calibration", record["pressure_calibration"])
            )
        if record.get("parameter_provenance"):
            lines.extend(
                details("Parameter provenance", record["parameter_provenance"])
            )
    lines.extend(["## Observation datasets", ""])
    datasets = document.get("datasets", [])
    if not datasets:
        lines.extend(["No datasets are declared in this material document.", ""])
    for dataset in datasets:
        lines.extend([f"### {text(dataset['identifier'])}", ""])
        lines.extend(
            metadata(
                {
                    k: dataset[k]
                    for k in (
                        "description",
                        "kind",
                        "reference",
                        "source_location",
                        "used_by_eos_records",
                        "uncertainty",
                        "notes",
                    )
                    if k in dataset
                }
            )
        )
        if dataset.get("resource"):
            resource = dataset["resource"]
            lines.extend(
                [
                    "",
                    f"[Observation resource]({SOURCE_URL}{quote(resource['path'])})",
                    f"— SHA-256 `{resource['sha256']}`.",
                    "",
                ]
            )
        else:
            lines.extend(
                ["", f"{len(dataset['rows'])} rows embedded in the EOSMAT source.", ""]
            )
    return "\n".join(line.rstrip() for line in lines).rstrip() + "\n"


def generated_pages() -> dict[str, str]:
    materials = {material.identifier: material for material in list_materials()}
    executable = {
        record.identifier
        for material in materials.values()
        for record in material.eos_records
    }
    pages = {}
    index = [
        "# Readable material summaries",
        "",
        _GENERATED,
        "",
        "Each sheet compares the stored EOS records and shows parameters, reported",
        "errors, reference states, calibration, usage qualifications and datasets.",
        "Deferred and diagnostic records remain visible. Automatic selections reflect",
        "the current catalog, including default holds and pressure-scale variants.",
        "",
        "These sheets are generated from EOSMAT. Edit the material source, then run",
        "`python -m scripts.generate_material_summaries`; `--check` detects drift.",
        "See [Reading and editing EOSMAT](../eosmat-authoring.md) for the simple template.",
        "",
        "| Material | Formula | Stored EOS records | Datasets |",
        "| --- | --- | --- | --- |",
    ]
    documents = [
        load_eosmat(path)
        for path in sorted((ROOT / "peritheos/data/materials").glob("*.eosmat"))
    ]
    for document in sorted(
        documents, key=lambda d: (d["name"].casefold(), d["identifier"])
    ):
        identifier = document["identifier"]
        material = materials.get(identifier)
        defaults = {}
        if material:
            for kind, record in (
                ("equilibrium", material.default_equilibrium_record()),
                ("hugoniot", material.default_hugoniot_record()),
            ):
                if record:
                    defaults[record.identifier] = kind
        pages[identifier + ".md"] = render_material(
            document, executable=executable, defaults=defaults
        )
        index.append(
            f"| [{text(document['name'])}]({identifier}.md) | "
            f"{text(document['formula'])} | {len(document['eos_records'])} | "
            f"{len(document.get('datasets', []))} |"
        )
    pages["index.md"] = "\n".join(index) + "\n"
    return pages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    pages = generated_pages()
    stale = [
        OUTPUT / name
        for name, payload in pages.items()
        if not (OUTPUT / name).exists()
        or (OUTPUT / name).read_text(encoding="utf-8") != payload
    ]
    obsolete = {
        path
        for path in OUTPUT.glob("*.md")
        if path.name not in pages and _GENERATED in path.read_text(encoding="utf-8")
    }
    if args.check:
        for path in stale + sorted(obsolete):
            print(f"Material summary needs regeneration: {path}")
        return int(bool(stale or obsolete))
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.write_text(pages[path.name], encoding="utf-8")
    for path in obsolete:
        path.unlink()
    print(f"Generated {len(pages) - 1} material summaries and their index.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
