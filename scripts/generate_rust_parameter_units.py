"""Repository maintenance: write the Rust copy of the coefficient unit table.

``check.why`` names a coefficient's unit with
:func:`peritheos._overview.parameter_unit`. The Rust reader derives the same
line, so ``crates/peritheos/src/eosmat/parameter_units.rs`` holds the two
tables that function reads (``MODEL_PARAMETER_UNITS`` and the units every
model shares), generated from the Python source; it is never edited by hand.

Run ``python scripts/generate_rust_parameter_units.py`` after changing the
tables in ``peritheos/_overview.py``; ``--check`` is read-only and fails when
the Rust file is out of date. This is not an installed-package tool.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from peritheos._overview import _COMMON_UNITS, MODEL_PARAMETER_UNITS  # noqa: E402

TARGET = ROOT / "crates/peritheos/src/eosmat/parameter_units.rs"


def _string(text: str) -> str:
    # A JSON string literal is a valid Rust literal for these ASCII texts.
    if not text.isascii():
        raise ValueError(f"unit table text must be ASCII: {text!r}")
    return json.dumps(text)


def render() -> str:
    """The Rust file's text."""
    model_rows = "".join(
        f"    ({_string(model)}, {_string(name)}, {_string(unit)}),\n"
        for model, units in sorted(MODEL_PARAMETER_UNITS.items())
        for name, unit in sorted(units.items())
    )
    common_rows = "".join(
        f"    ({_string(name)}, {_string(unit)}),\n"
        for name, unit in sorted(_COMMON_UNITS.items())
    )
    return (
        "//! Documented units of stored coefficients, for the `check.why` line.\n"
        "//!\n"
        "//! Generated by `scripts/generate_rust_parameter_units.py` from\n"
        "//! `MODEL_PARAMETER_UNITS` and the shared units in\n"
        '//! `peritheos/_overview.py`; do not edit. `"1"` marks a dimensionless\n'
        "//! coefficient.\n"
        "\n"
        "/// `(model, parameter, unit)` for coefficients whose unit depends on the "
        "model.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const MODEL_PARAMETER_UNITS: &[(&str, &str, &str)] = &[\n"
        f"{model_rows}"
        "];\n"
        "\n"
        "/// `(parameter, unit)` shared by every model.\n"
        "#[rustfmt::skip]\n"
        "pub(super) const COMMON_PARAMETER_UNITS: &[(&str, &str)] = &[\n"
        f"{common_rows}"
        "];\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    arguments = parser.parse_args(argv)
    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
    if arguments.check:
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run this script.")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current.")
        return 0
    if current != text:
        TARGET.write_text(text, encoding="utf-8")
        print(f"Wrote {TARGET.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
