use std::path::Path;

use peritheos::{load_eosmat, load_eosmat_str};

#[test]
fn ferrous_ringwoodite_staged_candidate_loads_round_trips_and_matches_quadrature() {
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data/ferrous-ringwoodite-staged.eosmat");
    let material = load_eosmat(path).unwrap();
    let static_record = material
        .record("ferrous_ringwoodite_finger_1979_bm2_ambient_cell_reconstruction")
        .unwrap();
    assert_eq!(static_record.document["record_kind"], "derived");
    assert_eq!(
        static_record.document["scientific_validation"]["status"],
        "primary_source_validated"
    );
    assert!((static_record.pressure(553.5, 296.15).unwrap() - 1.867_379_040_453_365).abs() < 1e-10);
    assert!((static_record.pressure(547.7, 296.15).unwrap() - 4.055_607_673_803_6).abs() < 1e-10);
    let record = material
        .record("ferrous_ringwoodite_armentrout_kavner_2011_bm2_mgd_candidate")
        .unwrap();
    assert_eq!(
        record.document["scientific_validation"]["status"],
        "not_reproduced"
    );
    assert_eq!(record.document["catalog_access"], "explicit_selection");
    assert_eq!(record.document["thermal"]["parameters"]["n"], 7.0);
    // Independent SI quadrature, not expected values generated by native code.
    for (p, t, volume) in [
        (5.0, 1000.0, 552.628_308_619_514_2),
        (10.0, 1500.0, 545.289_451_754_468),
        (24.0, 2000.0, 518.753_150_593_098),
    ] {
        assert!((record.volume(p, t).unwrap() - volume).abs() < 3e-8);
        assert!((record.pressure(volume, t).unwrap() - p).abs() < 3e-8);
    }
    let restored = load_eosmat_str(&material.to_json().unwrap()).unwrap();
    assert_eq!(restored.document, material.document);
}
