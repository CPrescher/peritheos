use std::path::Path;

use peritheos::{load_eosmat, load_eosmat_str};

#[test]
fn li_2002_published_record_executes_and_preserves_source_evidence() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../peritheos/data/materials/cementite.eosmat");
    if !path.is_file() {
        // Python catalog data are intentionally absent from the crates.io archive.
        return;
    }
    let material = load_eosmat(path).unwrap();
    let record = material.record("cementite_li_2002_bm3").unwrap();
    assert_eq!(record.reference_volume(), 155.28);
    // Independent Figure 2 reading, not a number generated by this implementation.
    assert!((record.volume(30.0, 300.0).unwrap() - 136.730_434_78).abs() < 0.12);
    // Independently measured Table 1 row 14 and its printed pressure width.
    assert!((record.pressure(136.68, 300.0).unwrap() - 30.5).abs() < 1.2);
    let volume = record.volume(20.0, 300.0).unwrap();
    assert!((record.pressure(volume, 300.0).unwrap() - 20.0).abs() < 1e-8);
    let restored = load_eosmat_str(&material.to_json().unwrap()).unwrap();
    assert_eq!(restored.document, material.document);
    assert_eq!(
        restored.record("cementite_li_2002_bm3").unwrap().document,
        record.document
    );
}
