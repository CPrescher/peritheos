def test_published_volumes_consistent_with_lattice_printing_without_replacement():
    raw, _ = rows()
    for r in raw:
        bounds = []
        for key in ("a_a", "b_a", "c_a"):
            x = Decimal(r[key])
            half = Decimal(10) ** x.as_tuple().exponent / 2
            bounds.append((float(x - half), float(x + half)))
        lo, hi = np.prod([b[0] for b in bounds]), np.prod([b[1] for b in bounds])
        assert lo - 0.005 <= float(r["volume_a3"]) <= hi + 0.005


