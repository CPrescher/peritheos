def test_preserved_source_hashes_when_local_sources_are_available():
    manifest = json.loads((DATA / "source-manifest.json").read_text())
    assert manifest["li_publication"]["doi"] == "10.1007/s00269-001-0224-4"
    for source in manifest["preserved_files"]:
        path = ROOT / source["path"]
        if path.exists():
            assert sha256(path) == source["sha256"]
    if PDF.exists():
        assert PDF.stat().st_size == 117927


def test_stored_reproduction_retains_original_tokens_and_current_arrays():
    stored = json.loads((ROOT / "docs/data/li-2002-fe3c-reproduction.json").read_text())
    for path, expected in stored["input_sha256"].items():
        assert sha256(ROOT / path) == expected
    assert stored["normalized_rows"] == rows()[1]
    assert stored["verdict"]["author_workflow"] == "not_recovered"
