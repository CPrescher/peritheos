def test_exact_source_equation_matches_existing_rust_evaluator_and_units():
    _, (_, v, _, _) = arrays()
    np.testing.assert_allclose(BM3(V0, *SOURCE).pressure(v), pressure(v), rtol=2e-13)
    for factor in (1 / 4, 1 / 16, 6.02214076e23 * 1e-24 / 4):
        np.testing.assert_allclose(
            pressure(v * factor, v0=V0 * factor), pressure(v), atol=1e-12
        )
    np.testing.assert_allclose(volume(pressure(v)), v, atol=2e-11)
    numerical = (pressure(v + 1e-4) - pressure(v - 1e-4)) / 2e-4
    np.testing.assert_allclose(dpdv(v), numerical, rtol=2e-8)


