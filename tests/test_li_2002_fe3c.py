def test_weighted_linear_solution_and_conditional_uncertainty_basis():
    pw = fit("pressure_width")
    np.testing.assert_allclose(pw["parameters"], linear_pressure_fit(), rtol=2e-8)
    ev = fit("effective_variance")
    np.testing.assert_allclose(ev["parameters"], [173.78786, 4.84972], atol=3e-5)
    np.testing.assert_allclose(
        ev["conditional_absolute_widths"], [6.19633, 0.774933], atol=3e-5
    )
    assert np.all(
        np.asarray(ev["residual_scaled_widths"]) < ev["conditional_absolute_widths"]
    )
    assert (
        abs(reference_pressure_sensitivity()["change_from_literal_Eq2_fit"][0]) < 0.01
    )


def test_orthogonal_replay_independently_checks_effective_variance():
    result = orthogonal_fit()
    np.testing.assert_allclose(result["parameters"], [173.78484, 4.85004], atol=3e-5)
    ev = fit("effective_variance")
    np.testing.assert_allclose(result["parameters"], ev["parameters"], atol=0.004)
    np.testing.assert_allclose(
        result["conditional_absolute_widths"],
        ev["conditional_absolute_widths"],
        rtol=0.0003,
    )


